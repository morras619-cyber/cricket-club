#!/usr/bin/env python3
"""Packs the painted shop/apartment tiles (img/shop) and the building banners (img/banner) into js/shoparts.js as data URIs,
so the game ships them as one file. Run from the repo root after changing a picture."""
import base64, io, glob, os
from PIL import Image

def uri(path, width=None, quality=80):
    im = Image.open(path).convert('RGB')
    if width and im.width > width: im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, 'WEBP', quality=quality)
    return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()

tiles = {os.path.basename(p)[:-5]: uri(p, 200, 80) for p in sorted(glob.glob('img/shop/*.webp'))}
banners = {os.path.basename(p)[:-5]: uri(p, 640, 72) for p in sorted(glob.glob('img/banner/*.webp'))}
def obj(d): return '{\n' + ''.join(f"  '{k}': '{v}',\n" for k, v in d.items()) + '}'
open('js/shoparts.js', 'w').write('// generated by tools/build_shoparts.py: painted tiles and banners as data URIs. Do not edit by hand.\n'
  f'export const TILES = {obj(tiles)};\nexport const BANNERS = {obj(banners)};\n')
