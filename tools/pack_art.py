"""Packs small painted images into js/packed.js as data URIs (the published game is at its file limit).
Run from the repo root with the loose files in place (git show <rev>:img/... to restore them); the images' bytes are unchanged."""
import base64, os

LOGOS = 'bengal comets elephants falcons harbour hawks iron jaguars kites lagoon lanterns lotus monsoon rockets sultans tempest'.split()
ICONS = 'allrounder deathKing eagleEye finisher hero mystery pace risingStar safeHands swingMaster'.split()
COINS = [f'coin-flip{i}' for i in range(1, 8)]

def uri(path):
    return 'data:image/webp;base64,' + base64.b64encode(open(path, 'rb').read()).decode()

def block(name, items, folder, prefix=''):
    rows = ',\n'.join(f"  '{n}': '{uri(f'{folder}/{prefix}{n}.webp')}'" for n in items)
    return f'export const {name} = {{\n{rows},\n}};\n'

out = '// Generated by tools/pack_art.py: small painted images as data URIs, so they cost no files of their own.\n'
out += block('CLUB_LOGOS', LOGOS, 'img', 'logo-') + block('CARD_ICONS', ICONS, 'img/cards/icons') + block('COIN_FRAMES', COINS, 'img/toss')
open('js/packed.js', 'w').write(out)
print(len(out))
