import test from 'node:test';
import assert from 'node:assert/strict';
const C = await import('../js/career.js');
const P = await import('../js/pacing.js');
const { SHOP } = C;
const DAY = 86400000;
const ctx = (now = 5 * DAY, trusted = true) => ({ now, trusted });
const club = () => { const c = C.newCareer(51); C.chooseClub(c, c.divisions.d3[0]); C.finishAuction(c); c.money = 50; return c; };
const bat = c => C.clubPlayers(c, c.club).find(p => p.role === 'bat');
const bowler = c => C.clubPlayers(c, c.club).find(p => p.bowl);

test('buying gear takes club cash, and the armoury has so many places', () => {
  const c = club(), m0 = c.money;
  const r = C.buyGear(c, 'blaster', ctx(0, false));
  assert.ok(r.ok); assert.ok(Math.abs(m0 - c.money - 0.5) < 0.011, 'full price without a server day');
  assert.ok(C.seasonBooks(c).out.buildings >= 0.5 - 0.001, 'written in the books');
  C.buyGear(c, 'blaster', ctx(0, false)); C.buyGear(c, 'blaster', ctx(0, false));
  assert.equal(C.shopOf(c).gear.length, 3);
  assert.equal(C.buyGear(c, 'blaster', ctx(0, false)).ok, false, 'three places at level 1');
  C.shopOf(c).level = 5; assert.equal(C.armourySlots(c), 6);
  C.shopOf(c).level = 10; assert.equal(C.armourySlots(c), 9);
  const poor = club(); poor.money = 0.1;
  assert.equal(C.buyGear(poor, 'thunder', ctx()).ok, false);
  assert.equal(C.buyGear(poor, 'nothing', ctx()).ok, false);
});
test('three deals a day, the same all day, cheaper in a bigger shop, each once', () => {
  const c = club(), d = C.dealsToday(c, 5 * DAY + 3 * 3600000);
  assert.equal(d.ids.length, 3); assert.equal(new Set(d.ids).size, 3);
  assert.deepEqual(C.dealsToday(c, 5 * DAY + 20 * 3600000).ids, d.ids, 'the same all day');
  const other = C.dealsToday(club(), 6 * DAY).ids;
  assert.ok(other.length === 3);
  const id = d.ids[0], full = C.gearPrice(c, id), off = C.gearPrice(c, id, true);
  assert.ok(off < full && Math.abs(off - full * 0.8) < 0.011, 'level 1: 20% off');
  C.shopOf(c).level = 10; assert.ok(Math.abs(C.gearPrice(c, id, true) - full * 0.6) < 0.011, 'level 10: 40% off');
  C.shopOf(c).level = 1;
  const m0 = c.money, r = C.buyGear(c, id, ctx(5 * DAY + 3600000));
  assert.ok(r.onDeal); assert.ok(Math.abs(m0 - c.money - off) < 0.011);
  const m1 = c.money, r2 = C.buyGear(c, id, ctx(5 * DAY + 3600000));
  assert.equal(r2.onDeal, false, 'the second one is at full price'); assert.ok(Math.abs(m1 - c.money - full) < 0.011);
  const next = C.dealsToday(c, 6 * DAY);
  assert.deepEqual(next.taken, {}, 'a new day, a new shelf');
  const notDeal = Object.keys(SHOP.GEAR).find(g => !C.dealsToday(c, 7 * DAY).ids.includes(g));
  assert.equal(C.buyGear(c, notDeal, ctx(7 * DAY)).onDeal, false);
});
test('a player carries one thing; grips are for bowlers; what he had goes back to the armoury', () => {
  const c = club();
  C.buyGear(c, 'blaster', ctx(0, false)); C.buyGear(c, 'edge', ctx(0, false)); C.buyGear(c, 'grips', ctx(0, false));
  const [a, b, g] = C.shopOf(c).gear, p = bat(c), nb = C.clubPlayers(c, c.club).find(x => !x.bowl);
  assert.ok(C.equipGear(c, a.id, p.id).ok);
  assert.ok(C.equipGear(c, b.id, p.id).ok);
  assert.equal(a.on, null, 'the first is back in the armoury'); assert.equal(b.on, p.id);
  assert.equal(C.equipGear(c, g.id, nb.id).ok, false, 'grips for a man who does not bowl');
  assert.equal(C.equipGear(c, g.id, 'nobody').ok, false);
  assert.ok(C.unequipGear(c, b.id).ok); assert.equal(b.on, null);
  assert.ok(C.discardGear(c, a.id).ok); assert.equal(C.shopOf(c).gear.length, 2);
});
test('gear gives rating in the match copies only, adds to chemistry, and caps at 99', () => {
  const c = club(); C.buyGear(c, 'thunder', ctx(0, false)); C.buyGear(c, 'sprint', ctx(0, false));
  const p = bat(c), q = bowler(c);
  C.equipGear(c, C.shopOf(c).gear[0].id, p.id); C.equipGear(c, C.shopOf(c).gear[1].id, q.id);
  const bonus = C.gearBonus(c);
  assert.deepEqual(bonus.get(p.id), { bat: 4, bowl: 0 }); assert.deepEqual(bonus.get(q.id), { bat: 1, bowl: 1 });
  const pool = C.clubPool(c, c.club), mine = C.matchPool(c, pool), r = id => mine.find(x => x.id === id), o = id => pool.find(x => x.id === id);
  assert.equal(r(p.id).bat, Math.min(99, o(p.id).bat + 4 + (C.chemBonus(c).get(p.id) || 0)));
  assert.equal(c.players[p.id].bat, o(p.id).bat, 'the saved player is not changed');
  p.bat = 98; const hi = C.matchPool(c, C.clubPool(c, c.club)).find(x => x.id === p.id);
  assert.equal(hi.bat, 99);
});
test('gear wears out after twenty matches the player takes part in, and then it is gone', () => {
  const c = club(); C.buyGear(c, 'blaster', ctx(0, false)); C.buyGear(c, 'edge', ctx(0, false));
  const [a, b] = C.shopOf(c).gear, p = bat(c), q = C.clubPlayers(c, c.club).find(x => x.id !== p.id);
  C.equipGear(c, a.id, p.id);
  for (let i = 0; i < 19; i++) C.gearAfterMatch(c, [p.id]);
  assert.equal(a.uses, 1); assert.equal(b.uses, SHOP.USES, 'not carried: no wear');
  C.gearAfterMatch(c, [q.id]); assert.equal(a.uses, 1, 'he sat this one out');
  C.gearAfterMatch(c, [p.id]);
  assert.deepEqual(C.shopOf(c).gear.map(g => g.id), [b.id], 'worn out and gone');
  assert.equal(C.gearBonus(c).size, 0);
});
test('looks cost diamonds, are kept, and can be switched on and off', () => {
  const c = club();
  assert.equal(C.buyLook(c, 'lights', 'gold').ok, false, 'no diamonds');
  P.addDiamonds(c, 100);
  assert.ok(C.buyLook(c, 'lights', 'gold').ok);
  assert.equal(P.buildOf(c).diamonds, 60);
  assert.equal(C.buyLook(c, 'lights', 'gold').ok, false, 'already yours');
  assert.equal(C.lookColour(c, 'lights'), '#ffd23f'); assert.equal(C.lookColour(c, 'trail'), null);
  C.setLook(c, 'lights', null); assert.equal(C.lookColour(c, 'lights'), null);
  assert.equal(C.setLook(c, 'lights', 'neon').ok, false, 'not bought');
  assert.ok(C.setLook(c, 'lights', 'gold').ok); assert.equal(C.lookColour(c, 'lights'), '#ffd23f');
  assert.equal(C.buyLook(c, 'hat', 'x').ok, false);
});
